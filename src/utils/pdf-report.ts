export interface MilkSalesReportInput {
  brand: ReportBrand;
  lang: ReportLang;
  entries: MilkEntry[];
  /** Human label of the filter, e.g. "This month" */
  periodLabel: string;
  /** Optional explicit range, used for the header when provided. */
  startDate?: string;
  endDate?: string;
  generatedAt?: Date;
}

export function buildMilkSalesReportHtml(input: MilkSalesReportInput): string {
  const { brand, lang } = input;
  const L = LABELS[lang];
  const entries = [...input.entries].sort((a, b) =>
    a.date === b.date ? (a.shift === b.shift ? a.id - b.id : a.shift === 'Morning' ? -1 : 1) : a.date < b.date ? -1 : 1
  );

  const totalLiters = entries.reduce((s, e) => s + e.liters, 0);
  const totalAmount = entries.reduce((s, e) => s + e.total_amount, 0);
  const fatWeighted = totalLiters > 0 ? entries.reduce((s, e) => s + e.fat_percentage * e.liters, 0) / totalLiters : 0;
  const avgRate = totalLiters > 0 ? totalAmount / totalLiters : 0;
  const morning = entries.filter((e) => e.shift === 'Morning').reduce((s, e) => s + e.liters, 0);
  const evening = totalLiters - morning;

  const first = entries[0]?.date;
  const last = entries[entries.length - 1]?.date;
  const start = input.startDate ?? first;
  const end = input.endDate ?? last;
  const periodText = start && end ? `${input.periodLabel} · ${fmtPeriod(start, end)}` : input.periodLabel;

  // By buyer
  const byBuyer = new Map<string, { liters: number; amount: number; count: number }>();
  for (const e of entries) {
    const cur = byBuyer.get(e.buyer_name) ?? { liters: 0, amount: 0, count: 0 };
    cur.liters += e.liters;
    cur.amount += e.total_amount;
    cur.count += 1;
    byBuyer.set(e.buyer_name, cur);
  }
  const buyerRows = [...byBuyer.entries()]
    .sort((a, b) => b[1].amount - a[1].amount)
    .map(
      ([name, v]) => `<tr>
  <td>${escapeHtml(name)}</td><td class="num">${fmtNum(v.count)}</td><td class="num">${fmtNum(v.liters, 1)}</td><td class="num">${fmtRs(v.amount)}</td>
  <td class="num">${totalAmount > 0 ? pct((v.amount / totalAmount) * 100) : '—'}</td>
</tr>`
    )
    .join('');

  // Detail grouped by date with day subtotals
  const detail: string[] = [];
  let i = 0;
  while (i < entries.length) {
    const date = entries[i].date;
    let dayLiters = 0;
    let dayAmount = 0;
    while (i < entries.length && entries[i].date === date) {
      const e = entries[i];
      dayLiters += e.liters;
      dayAmount += e.total_amount;
      detail.push(`<tr>
  <td>${escapeHtml(fmtDayShort(e.date))}</td>
  <td>${escapeHtml(shiftLabel(L, e.shift))}</td>
  <td>${escapeHtml(e.buyer_name)}${e.notes ? `<div class="muted small">${escapeHtml(e.notes)}</div>` : ''}</td>
  <td class="num">${fmtNum(e.liters, 1)}</td>
  <td class="num">${e.fat_percentage ? fmtNum(e.fat_percentage, 1) : '—'}</td>
  <td class="num">${fmtNum(e.rate_per_liter, 0)}</td>
  <td class="num">${fmtRs(e.total_amount)}</td>
</tr>`);
      i++;
    }
    detail.push(
      `<tr class="daytotal"><td colspan="3">${escapeHtml(L.dayTotal)}</td><td class="num">${fmtNum(dayLiters, 1)}</td><td></td><td></td><td class="num">${fmtRs(dayAmount)}</td></tr>`
    );
  }

  const body = `
${kpiRow([
  kpi(L.totalSales, fmtRs(totalAmount), `${fmtNum(entries.length)} ${L.entries}`),
  kpi(L.volume, `${fmtNum(totalLiters, 1)} L`, `${L.morning} ${fmtNum(morning, 1)} · ${L.evening} ${fmtNum(evening, 1)}`),
  kpi(L.avgRate, `${fmtRs(avgRate)} / L`, `${L.avgFat}: ${fmtNum(fatWeighted, 1)}%`),
])}

${
  entries.length === 0
    ? `<p class="muted">${escapeHtml(L.noRecords)}</p>`
    : `
<div class="section">${escapeHtml(L.byBuyer)}</div>
<table class="data">
  <thead><tr><th>${escapeHtml(L.buyer)}</th><th class="num">${escapeHtml(L.entries)}</th><th class="num">${escapeHtml(L.liters)}</th><th class="num">${escapeHtml(L.amount)}</th><th class="num">${escapeHtml(L.share)}</th></tr></thead>
  <tbody>${buyerRows}</tbody>
  <tfoot><tr><td>${escapeHtml(L.total)}</td><td class="num">${fmtNum(entries.length)}</td><td class="num">${fmtNum(totalLiters, 1)}</td><td class="num">${fmtRs(totalAmount)}</td><td class="num">100%</td></tr></tfoot>
</table>

<div class="section">${escapeHtml(L.details)}</div>
<table class="data">
  <thead><tr><th>${escapeHtml(L.date)}</th><th>${escapeHtml(L.session)}</th><th>${escapeHtml(L.buyer)}</th><th class="num">${escapeHtml(L.liters)}</th><th class="num">${escapeHtml(L.fat)}</th><th class="num">${escapeHtml(L.rate)}</th><th class="num">${escapeHtml(L.amount)}</th></tr></thead>
  <tbody>${detail.join('')}</tbody>
  <tfoot><tr><td colspan="3">${escapeHtml(L.total)}</td><td class="num">${fmtNum(totalLiters, 1)}</td><td></td><td></td><td class="num">${fmtRs(totalAmount)}</td></tr></tfoot>
</table>`
}`;

  return renderDocument({
    lang,
    brand,
    title: L.milkReportTitle,
    periodText,
    generatedAt: input.generatedAt ?? new Date(),
    body,
  });
}

