/** e.g. dairyflow_weekly_report_2026-10-09_to_2026-10-15.pdf */
export function reportFileName(prefix: string, start?: string, end?: string): string {
  const safe = prefix.replace(/[^a-z0-9_-]/gi, '_').toLowerCase();
  const range = start && end ? (start === end ? `_${start}` : `_${start}_to_${end}`) : '';
  return `dairyflow_${safe}${range}.pdf`;
}

/** First and last day (YYYY-MM-DD) of the month that contains `iso`. */
export function monthRangeOf(iso: string): { start: string; end: string } {
  const p = parseYmd(iso) ?? { y: new Date().getFullYear(), m: new Date().getMonth() + 1, d: 1 };
  const pad = (n: number) => String(n).padStart(2, '0');
  const lastDay = new Date(Date.UTC(p.y, p.m, 0)).getUTCDate();
  return { start: `${p.y}-${pad(p.m)}-01`, end: `${p.y}-${pad(p.m)}-${pad(lastDay)}` };
}

/** Month range shifted by `delta` months (-1 = previous month). */
export function shiftMonthRange(iso: string, delta: number): { start: string; end: string } {
  const p = parseYmd(iso) ?? { y: new Date().getFullYear(), m: new Date().getMonth() + 1, d: 1 };
  const shifted = new Date(Date.UTC(p.y, p.m - 1 + delta, 1));
  const pad = (n: number) => String(n).padStart(2, '0');
  return monthRangeOf(`${shifted.getUTCFullYear()}-${pad(shifted.getUTCMonth() + 1)}-01`);
}
