/**
 * In right-to-left (Urdu) documents, Latin/number runs such as "9 Oct 2026 – 15 Oct 2026",
 * "Rs 22,500" or a phone number are reordered by the bidi algorithm unless they are isolated.
 * Wrap those runs, in text nodes only (never inside tags or the stylesheet), as LTR isolates.
 */
export function isolateLtrRuns(html: string): string {
  const run = /[A-Za-z0-9](?:[A-Za-z0-9.,:%+\-–−×/@&;#_ ]*[A-Za-z0-9%;.])?/g;
  return html
    .split(/(<[^>]*>)/)
    .map((part) => (part.startsWith('<') ? part : part.replace(run, (m) => `<span class="ltr">${m}</span>`)))
    .join('');
}

interface ShellOptions {
  lang: ReportLang;
  brand: ReportBrand;
  title: string;
  /** e.g. "15 Oct 2026 – 21 Oct 2026" */
  periodText?: string;
  generatedAt: Date;
  /** Extra header cells (label, value) shown after period/generated. */
  extraMeta?: [string, string][];
  body: string;
}

function renderDocument(o: ShellOptions): string {
  const L = LABELS[o.lang];
  const rtl = o.lang === 'ur';
  const contact = [o.brand.phone, o.brand.email].filter(Boolean).map(escapeHtml).join(' · ');

  const metaCells: [string, string][] = [];
  if (o.periodText) metaCells.push([L.period, escapeHtml(o.periodText)]);
  metaCells.push([L.generated, escapeHtml(fmtGenerated(o.generatedAt))]);
  if (o.brand.ownerName) metaCells.push([L.owner, escapeHtml(o.brand.ownerName)]);
  if (contact) metaCells.push([L.contact, contact]);
  for (const cell of o.extraMeta ?? []) metaCells.push(cell);

  // Rows of up to 3 cells keep the header compact and aligned
  const rows: string[] = [];
  for (let i = 0; i < metaCells.length; i += 3) {
    const slice = metaCells.slice(i, i + 3);
    rows.push(
      `<tr>${slice
        .map(([k, v]) => `<td><span class="k">${escapeHtml(k)}</span>${v}</td>`)
        .join('')}${'<td></td>'.repeat(3 - slice.length)}</tr>`
    );
  }

  const metaRows = rtl ? isolateLtrRuns(rows.join('')) : rows.join('');
  const bodyHtml = rtl ? isolateLtrRuns(o.body) : o.body;
  const footerText = `${L.footer} · ${fmtGenerated(o.generatedAt)}`;

  return `<!DOCTYPE html>
<html lang="${o.lang}" dir="${rtl ? 'rtl' : 'ltr'}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(o.title)}</title>
<style>${CSS}</style>
</head>
<body class="${rtl ? 'rtl' : ''}">
<div class="hero">
  <div class="brandline">${escapeHtml(L.app)}</div>
  <div class="title">${escapeHtml(o.title)}</div>
  <div class="farm">${escapeHtml(o.brand.farmName)}</div>
  <table class="metatable">${metaRows}</table>
</div>
<div class="content">
${bodyHtml}
<div class="footer">${rtl ? isolateLtrRuns(escapeHtml(footerText)) : escapeHtml(footerText)}</div>
</div>
</body>
</html>`;
}

function kpi(label: string, value: string, sub?: string, cls = ''): string {
  return `<td class="kpi"><div class="l">${escapeHtml(label)}</div><div class="v ${cls}">${value}</div>${
    sub ? `<div class="s">${escapeHtml(sub)}</div>` : ''
  }</td>`;
}

function kpiRow(cells: string[], perRow = 3): string {
  const rows: string[] = [];
  for (let i = 0; i < cells.length; i += perRow) {
    const slice = cells.slice(i, i + perRow);
    rows.push(`<tr>${slice.join('')}${'<td></td>'.repeat(perRow - slice.length)}</tr>`);
  }
  return `<table class="kpis" role="presentation">${rows.join('<tr><td colspan="' + perRow + '" style="height:8px"></td></tr>')}</table>`;
}

function bar(percent: number): string {
  const w = Math.max(0, Math.min(100, Number.isFinite(percent) ? percent : 0));
  return `<div class="bar"><span style="width:${w.toFixed(1)}%"></span></div>`;
}

