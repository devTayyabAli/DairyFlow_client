export function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function fmtNum(value: number, decimals = 0): string {
  const v = Number.isFinite(value) ? value : 0;
  const [intPart, decPart] = Math.abs(v).toFixed(decimals).split('.');
  const grouped = intPart.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  const body = decPart ? `${grouped}.${decPart}` : grouped;
  // Avoid printing "-0"
  return v < 0 && Number(Math.abs(v).toFixed(decimals)) !== 0 ? `-${body}` : body;
}

export function fmtRs(value: number): string {
  const rounded = Math.round(Number.isFinite(value) ? value : 0);
  return rounded < 0 ? `-Rs ${fmtNum(Math.abs(rounded))}` : `Rs ${fmtNum(rounded)}`;
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const DAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

function parseYmd(iso: string): { y: number; m: number; d: number } | null {
  const match = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso ?? '');
  if (!match) return null;
  return { y: Number(match[1]), m: Number(match[2]), d: Number(match[3]) };
}

/** "15 Oct 2026" */
export function fmtDate(iso: string): string {
  const p = parseYmd(iso);
  return p ? `${p.d} ${MONTHS[p.m - 1] ?? ''} ${p.y}` : iso;
}

/** "Thu, 15 Oct" */
export function fmtDayShort(iso: string): string {
  const p = parseYmd(iso);
  if (!p) return iso;
  const dow = new Date(Date.UTC(p.y, p.m - 1, p.d)).getUTCDay();
  return `${DAYS[dow]}, ${p.d} ${MONTHS[p.m - 1] ?? ''}`;
}

export function fmtPeriod(start: string, end: string): string {
  return start === end ? fmtDate(start) : `${fmtDate(start)} – ${fmtDate(end)}`;
}

/** Date-only (no time zone surprises) timestamp for "Generated on". */
export function fmtGenerated(now: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${now.getDate()} ${MONTHS[now.getMonth()]} ${now.getFullYear()}, ${pad(now.getHours())}:${pad(now.getMinutes())}`;
}

const pct = (n: number) => `${fmtNum(n, 1)}%`;

